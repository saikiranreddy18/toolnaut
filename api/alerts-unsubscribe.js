// /api/alerts-unsubscribe?token=<uuid> — the link in every alert email.
//
// GET NEVER DELETES. It used to: a single GET removed the subscriber row. Mail
// providers and security gateways fetch every link in an incoming message to
// scan it — Gmail's link protection, Outlook Safe Links, corporate filters —
// so the unsubscribe link fired the moment the first digest arrived. Nobody
// clicked anything, and no second email was ever sent. That is the bug behind
// "I got one alert, and then nothing".
//
// So GET shows a page with a button, and only POST removes the row. Scanners
// fetch; they do not submit forms. The same POST serves RFC 8058 one-click
// unsubscribe (the List-Unsubscribe-Post header alerts-send attaches), which
// Gmail and Yahoo send from their own Unsubscribe button, and which is a POST
// by definition.
//
// The token is a per-subscriber uuid generated by the database, so the URL
// can't be guessed from an email address.
import { alertsConfigured, rest } from './_alerts.js'

const TOKEN_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

function page(title, body, extra = '') {
  return `<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex">
<title>${title}</title>
<body style="font-family:system-ui,sans-serif;background:#0a0a12;color:#e5e7eb;display:grid;place-items:center;min-height:100vh;margin:0;">
<div style="text-align:center;padding:24px;max-width:420px;">
  <h1 style="font-size:20px;">${title}</h1>
  <p style="color:#9ca3af;font-size:14px;line-height:1.5;">${body}</p>
  ${extra}
  <p style="margin-top:18px;"><a href="/" style="color:#a3ff2e;font-size:13px;">← Back to Toolnaut</a></p>
</div>`
}

export default async function handler(req, res) {
  const token = String(req.query?.token || '')
  res.setHeader('content-type', 'text/html; charset=utf-8')

  // uuid shape only — anything else never reaches the database
  if (!TOKEN_RE.test(token) || !alertsConfigured) {
    return res.status(400).send(page('That link doesn’t work', 'The unsubscribe link is invalid or alerts are not set up.'))
  }

  if (req.method === 'GET' || req.method === 'HEAD') {
    // Deliberately read-only. See the note at the top of this file.
    return res.status(200).send(page(
      'Stop new-tool alerts?',
      'You will stop getting an email when the radar finds tools that fit you. You can turn alerts back on any time in Settings.',
      `<form method="post" action="/api/alerts-unsubscribe?token=${token}">
    <button type="submit" style="font:inherit;font-weight:700;background:#a3ff2e;color:#000;border:2px solid #000;border-radius:999px;padding:10px 22px;cursor:pointer;">Unsubscribe</button>
  </form>`,
    ))
  }

  if (req.method !== 'POST') {
    res.setHeader('Allow', 'GET, HEAD, POST')
    return res.status(405).send(page('Not allowed', 'Open the link from your email to unsubscribe.'))
  }

  const del = await rest(`alert_subscribers?unsubscribe_token=eq.${token}`, {
    method: 'DELETE',
    headers: { prefer: 'return=representation' },
  })
  if (!del.ok) {
    console.error('alerts-unsubscribe delete', del.status, del.text?.slice(0, 200))
    return res.status(502).send(page('That didn’t go through', 'We could not update your settings just now. Try the link again in a minute.'))
  }
  // Deleting an already-deleted token lands here too — still success from the
  // person's point of view: they are not subscribed.
  const removed = Array.isArray(del.json) && del.json.length > 0
  return res.status(200).send(
    removed
      ? page('You’re unsubscribed', 'No more new-tool alerts to this address. Turn them back on any time in Settings.')
      : page('Already unsubscribed', 'This address wasn’t on the alert list — nothing to do.'),
  )
}
